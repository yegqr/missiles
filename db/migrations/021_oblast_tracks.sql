-- 021: цілі над областю як окрема величина
--
-- Канал 1439 разів написав про ціль над Київською областю, не згадавши міста:
-- «БпЛА курсом на Вишгород», «повз Славутич курсом на південь». Досі ці
-- повідомлення просто зникали: у лейбл їх пускати не можна (удар по Броварах
-- не є ударом по Києву), а окремої величини не існувало.
--
-- Тепер scope='kyiv_obl' — третій, поряд із 'kyiv' (місто) і 'ua' (країна).
-- У ЛЕЙБЛ вона не входить за побудовою; вона потрібна як ОЗНАКА: ціль за
-- 30 км від міста — це те, що відомо до відсічки й може щось означати.

ALTER TABLE attack_observations DROP CONSTRAINT attack_observations_scope_check;
ALTER TABLE attack_observations ADD CONSTRAINT attack_observations_scope_check
    CHECK (scope IN ('kyiv', 'kyiv_obl', 'ua'));

COMMENT ON COLUMN attack_observations.scope IS
  'kyiv — місто; kyiv_obl — Київська область без міста; ua — країна. '
  'Три різні величини, які НІКОЛИ не складаються між собою.';
