#!/usr/bin/env bash
# Щоденний прогноз на добу нальоту, що починається о 12:00 за Києвом.
#
# ЧОМУ ТУТ ВАРТОВИЙ, А НЕ ПРОСТО ЧАС У CRON. Debian-івський cron ігнорує
# CRON_TZ і працює за UTC, а Київ узимку UTC+2, улітку UTC+3. Запис «5 12 * * *»
# стріляв о 15:05 за Києвом — через три години після відсічки, заявленої в
# методології. Тому cron будить скрипт двічі (09:05 і 10:05 UTC, тобто 12:05
# київського часу влітку та взимку), а скрипт сам перевіряє київську годину
# і зайвий запуск тихо пропускає.
set -euo pipefail
cd "$(dirname "$0")/.."

HOUR=$(TZ=Europe/Kyiv date +%-H)
if [ "${1:-}" != "--force" ] && [ "$HOUR" != "12" ]; then
    echo "$(TZ=Europe/Kyiv date '+%F %T') київська година $HOUR — не час відсічки, пропущено"
    exit 0
fi

# Прогноз може впасти на одному з горизонтів. Сайт перебудовується в будь-якому
# разі: краще сторінка з одним числом і чесним «прогноз ще не видано» на другій
# вкладці, ніж сторінка, що застрягла на вчорашній добі.
.venv/bin/python ml/final.py || echo "predict: ml/final.py завершився з помилкою"
exec .venv/bin/python site/build.py
